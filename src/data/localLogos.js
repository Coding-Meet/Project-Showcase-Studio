export function findLocalLogo(techName) {
  if (!techName || typeof techName !== 'string') return null;
  const clean = techName.trim().toLowerCase();
  const cleanNoPunct = clean.replace(/[^a-z0-9]/g, '');

  for (const item of LOCAL_LOGOS) {
    if (item.aliases.includes(clean) || item.aliases.includes(cleanNoPunct)) {
      return item;
    }
    // Partial inclusion match (e.g. "Jetpack Compose" matches "compose")
    for (const alias of item.aliases) {
      if (alias.length >= 4 && (clean.includes(alias) || alias.includes(clean))) {
        return item;
      }
    }
  }
  return null;
}

export function resolveLocalLogoSrc(techName, variant = 'icon') {
  const match = findLocalLogo(techName);
  if (!match) return null;
  if (variant === 'wordmark' && match.hasWordmark && match.wordmarkSrc) {
    return match.wordmarkSrc;
  }
  return match.iconSrc || match.wordmarkSrc;
}
